-- 주문별 결제 금액 요약 (JOIN 미리 보기)
SELECT '=== 주문별 결제 금액 요약 ===' AS '';
SELECT
    o.order_id,
    c.name                              AS 고객명,
    o.order_date,
    SUM(d.quantity * d.unit_price)      AS 결제금액,
    o.status
FROM orders o
JOIN customer     c ON o.customer_id = c.customer_id
JOIN order_detail d ON o.order_id    = d.order_id
GROUP BY o.order_id, c.name, o.order_date, o.status
ORDER BY o.order_id;
